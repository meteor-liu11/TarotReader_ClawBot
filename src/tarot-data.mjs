// ── 组装 78 张牌 ────────────────────────────────────────
export const CARDS = (() => {
  const out = [];
  for (const [n, en, zh, up, rev, proto] of MAJOR) {
    const num = String(n).padStart(2, '0');
    const file = n === 0 ? '00_Fool.jpg' : `${num}_${en.replace(/^The /, '').replace(/\s+/g, '_')}.jpg`;
    out.push({
      id: `major-${num}`,
      num,
      name: zh,
      nameEn: en,
      arcana: 'major',
      suit: null,
      rank: n,
      upright: up.split(','),
      reversed: rev.split(','),
      prototype: proto,
      img: file,
    });
  }
  for (const [suit, ranks] of Object.entries(MINOR)) {
    for (const [rank, [up, rev]] of Object.entries(ranks)) {
      const r = Number(rank);
      const num = String(r).padStart(2, '0');
      out.push({
        id: `${suit}-${num}`,
        num,
        name: `${SUITS[suit].name}${r <= 10 ? ['', 'Ace', '二', '三', '四', '五', '六', '七', '八', '九', '十'][r] : ['', '', '', '', '', '', '', '', '', '', '', '侍从', '骑士', '王后', '国王'][r]}`,
        nameEn: `${['', 'Ace', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Page', 'Knight', 'Queen', 'King'][r]} of ${SUITS[suit].en}`,
        arcana: 'minor',
        suit,
        rank: r,
        upright: up.split(','),
        reversed: rev.split(','),
        // 小阿卡纳的原型直接用它的首要关键词，避免在解读里漏出分类法原文
        prototype: up.split(',')[0],
        img: `${SUITS[suit].slug}${num}.jpg`,
      });
    }
  }
  return out;
})();

export const CARDS_BY_ID = new Map(CARDS.map((c) => [c.id, c]));

